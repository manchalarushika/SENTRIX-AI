import { Alert, Card, Empty, Space, Spin, Tag, Tooltip, Typography } from "antd";
import type { ReactNode } from "react";
import dayjs from "dayjs";
import relativeTime from "dayjs/plugin/relativeTime";
import utc from "dayjs/plugin/utc";

dayjs.extend(relativeTime);
dayjs.extend(utc);

export const SEVERITY_COLOR: Record<string, string> = {
  info: "#64748b",
  low: "#22c55e",
  medium: "#eab308",
  high: "#f97316",
  critical: "#ef4444",
};

export const STATUS_COLOR: Record<string, string> = {
  open: "red",
  investigating: "orange",
  contained: "blue",
  resolved: "green",
  closed: "default",
  false_positive: "purple",
  proposed: "gold",
  approved: "blue",
  pending_manual: "geekblue",
  dispatched: "cyan",
  completed: "green",
  rejected: "default",
  failed: "red",
  superseded: "default",
  success: "green",
  error: "red",
  skipped: "default",
};

const METHOD_LABEL: Record<string, { label: string; color: string; tip: string }> = {
  deterministic: { label: "Deterministic", color: "blue", tip: "Rule-based / algorithmic - same input, same output" },
  "machine-learning": { label: "ML", color: "purple", tip: "Statistical baselines + Isolation Forest (scikit-learn)" },
  simulation: { label: "Simulation", color: "cyan", tip: "Seeded Monte Carlo simulation (reproducible)" },
  retrieval: { label: "Retrieval", color: "geekblue", tip: "TF-IDF retrieval over the threat-intel knowledge base" },
  llm: { label: "LLM", color: "magenta", tip: "Generated by a large language model - verify before acting" },
};

export function SeverityTag({ value }: { value: string }) {
  return (
    <Tag color={SEVERITY_COLOR[value] ?? "#64748b"} style={{ color: "#0b1220", fontWeight: 600, textTransform: "uppercase" }}>
      {value}
    </Tag>
  );
}

export function StatusTag({ value }: { value: string }) {
  return <Tag color={STATUS_COLOR[value] ?? "default"}>{value.replace(/_/g, " ")}</Tag>;
}

export function MethodTag({ method }: { method: string }) {
  const m = METHOD_LABEL[method] ?? { label: method, color: "default", tip: method };
  return (
    <Tooltip title={m.tip}>
      <Tag color={m.color}>{m.label}</Tag>
    </Tooltip>
  );
}

export function RiskBar({ value }: { value: number }) {
  const color = value >= 75 ? SEVERITY_COLOR.critical : value >= 50 ? SEVERITY_COLOR.high : value >= 25 ? SEVERITY_COLOR.medium : SEVERITY_COLOR.low;
  return (
    <Space size={6}>
      <div style={{ width: 64, height: 6, background: "rgba(148,163,184,.2)", borderRadius: 3 }}>
        <div style={{ width: `${Math.min(100, value)}%`, height: 6, background: color, borderRadius: 3 }} />
      </div>
      <span style={{ fontVariantNumeric: "tabular-nums" }}>{value.toFixed(0)}</span>
    </Space>
  );
}

export function PageHeader({ title, subtitle, extra }: { title: string; subtitle?: string; extra?: ReactNode }) {
  return (
    <div className="page-header">
      <div>
        <Typography.Title level={3} style={{ margin: 0 }}>{title}</Typography.Title>
        {subtitle && <Typography.Text type="secondary">{subtitle}</Typography.Text>}
      </div>
      {extra && <Space wrap>{extra}</Space>}
    </div>
  );
}

export function Kpi({ label, value, hint, color }: { label: string; value: ReactNode; hint?: ReactNode; color?: string }) {
  return (
    <Card size="small" className="kpi">
      <div className="kpi-label">{label}</div>
      <div className="kpi-value" style={{ color }}>{value}</div>
      {hint && <div className="kpi-hint">{hint}</div>}
    </Card>
  );
}

export function Loadable({ loading, error, empty, children }: { loading: boolean; error: string | null; empty?: boolean; children: ReactNode }) {
  if (error) return <Alert type="error" showIcon message="Could not load data" description={error} />;
  if (loading) return <div style={{ padding: 48, textAlign: "center" }}><Spin /></div>;
  if (empty) return <Empty description="No data yet - ingest events or load the demo from Settings" />;
  return <>{children}</>;
}

export const fmtTime = (s?: string | null) => (s ? dayjs.utc(s).local().format("YYYY-MM-DD HH:mm:ss") : "-");
export const fromNow = (s?: string | null) => (s ? dayjs.utc(s).fromNow() : "-");
export const money = (n: number) => `$${Math.round(n).toLocaleString()}`;
export const pct = (n: number) => `${(n * 100).toFixed(0)}%`;
