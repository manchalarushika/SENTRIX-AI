"""Incident report generation (Markdown)."""

from __future__ import annotations

from sqlalchemy import select
from sqlalchemy.orm import Session

from sentrix import APP_NAME, __version__
from sentrix.db.models import Incident, ResponseAction, SecurityEvent, utcnow


def _esc(s: object) -> str:
    return str(s if s is not None else "").replace("|", "\\|").replace("\n", " ")


def incident_report_markdown(db: Session, inc: Incident) -> str:
    a = inc.analysis or {}
    events = db.scalars(select(SecurityEvent).where(SecurityEvent.incident_id == inc.id)
                        .order_by(SecurityEvent.timestamp)).all()
    actions = db.scalars(select(ResponseAction).where(ResponseAction.incident_id == inc.id)
                         .order_by(ResponseAction.id)).all()
    council = a.get("council", {})
    xai = a.get("xai", {})
    llm = a.get("llm", {})
    L = [
        f"# {inc.ref}: {inc.title}",
        "",
        f"*Generated by {APP_NAME} v{__version__} on {utcnow().isoformat(timespec='seconds')} UTC*",
        "",
        "| Field | Value |", "|---|---|",
        f"| Status | {inc.status} |", f"| Severity | {inc.severity} |",
        f"| Category | {inc.category} |", f"| Risk score | {inc.risk_score:.0f}/100 |",
        f"| Confidence | {inc.confidence:.2f} |",
        f"| First / last seen (UTC) | {inc.first_seen:%Y-%m-%d %H:%M} / {inc.last_seen:%Y-%m-%d %H:%M} |",
        f"| Hosts | {', '.join(inc.hostnames) or '-'} |", f"| Users | {', '.join(inc.users) or '-'} |",
        f"| MITRE tactics | {', '.join(inc.tactics) or '-'} |",
        f"| MITRE techniques | {', '.join(inc.techniques) or '-'} |",
        f"| Assignee | {inc.assignee or '-'} |",
        "", "## Summary", "", inc.summary or "Not yet analysed.", "",
    ]
    if xai.get("narrative"):
        L += ["## Explainable AI narrative (deterministic)", ""] + [f"- {n}" for n in xai["narrative"]] + [""]
    if llm.get("status") == "ok":
        c = llm["content"]
        L += [f"## LLM analysis ({llm['provider']}/{llm['model']}) - verify before acting", "",
              c["executive_summary"], "", c["attack_narrative"], "", "**Recommended next steps:**", ""]
        L += [f"- {s}" for s in c["recommended_next_steps"]] + [""]
    if council:
        L += ["## AI Council decision", "", council.get("rationale", ""), "",
              "| Agent | Effective weight | Preferred option | Reason |", "|---|---|---|---|"]
        L += [f"| {v['agent']} | {v['effective_weight']:.2f} | {_esc(v['preferred_name'])} | {_esc(v['reason'])} |"
              for v in council.get("votes", [])]
        L += ["", "| Option | Consensus score |", "|---|---|"]
        L += [f"| {_esc(r['name'])} | {r['score']:.3f} |" for r in council.get("ranking", [])] + [""]
    if actions:
        L += ["## Response actions", "", "| # | Action | Target | Risk | Status | Reviewed by |", "|---|---|---|---|---|---|"]
        L += [f"| {x.id} | {_esc(x.description)} | {_esc(x.target)} | {x.risk_level} | {x.status} | "
              f"{_esc(x.reviewed_by or '-')} |" for x in actions] + [""]
    L += ["## Event timeline", "", "| Time (UTC) | Event | Host | User | Technique | Threat |", "|---|---|---|---|---|---|"]
    L += [f"| {e.timestamp:%Y-%m-%d %H:%M:%S} | {_esc(e.event_type)} | {_esc(e.hostname or '-')} | "
          f"{_esc(e.user or '-')} | {_esc(e.mitre_technique or '-')} | {e.threat_score:.0f} |" for e in events]
    if inc.notes:
        L += ["", "## Analyst notes", ""] + [f"- **{n.author}** ({n.created_at:%Y-%m-%d %H:%M}): {n.body}"
                                             for n in inc.notes]
    return "\n".join(L) + "\n"
